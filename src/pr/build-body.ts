import { extractTaggedBlock } from "../agents/run-agent.js";
import {
  escapeCodeSpan,
  escapeMarkdownText,
  singleLine,
} from "../format/markdown.js";
import type {
  FixIterationResult,
  InvestigationResult,
  SentryIssueContext,
} from "../types.js";

export function buildPrBody(
  issue: SentryIssueContext,
  investigation: InvestigationResult,
  finalIteration: FixIterationResult,
  fingerprint?: string,
): string {
  const { fixerOutput } = finalIteration;
  const rootCause =
    extractTaggedBlock(fixerOutput, "ROOT_CAUSE") || investigation.rootCause;
  const fixSummary = extractTaggedBlock(fixerOutput, "FIX_SUMMARY");
  const hardProof = extractTaggedBlock(fixerOutput, "HARD_PROOF");
  const traceTable = extractTaggedBlock(fixerOutput, "TRACE_ALIGNMENT");
  const title = escapeCodeSpan(singleLine(issue.title, 200));
  const dedupeLine = fingerprint
    ? `- **Dedupe key:** \`sentry-dedupe:${fingerprint}\``
    : "";

  return `## Sentry issue

- **Issue:** \`${title}\`
- **URL:** ${issue.issueUrl}
- **ID:** \`${escapeCodeSpan(issue.issueId)}\`
${dedupeLine}
${issue.environment ? `- **Environment:** ${escapeMarkdownText(singleLine(issue.environment, 80))}` : ""}
${issue.count != null ? `- **Event count:** ${issue.count}` : ""}
${issue.culprit ? `- **Culprit:** \`${escapeCodeSpan(singleLine(issue.culprit, 200))}\`` : ""}

> Automated fix from Sentry. **Human review required** — do not merge without verifying root cause and proof.
> Agent-reported test output is not sufficient: require host CI green on the claimed regression.
> Duplicate Sentry events/issues with the same fingerprint are skipped while this PR is open.

## Root cause

${rootCause || "_Investigation output did not include a structured root cause. See agent transcript._"}

## Fix

${fixSummary || "_See changed files and fixer transcript._"}

## Hard proof

${hardProof || defaultHardProof(finalIteration)}

## Trace alignment

${traceTable || "_No frame-to-code mapping provided. Cross-check stack trace against the diff._"}

## Agent metadata

- Skeptic verdict: **${finalIteration.skepticReport.verdict}**
- Block/review round: ${finalIteration.iteration} (max 3)
- Regression spec: ${finalIteration.regressionSpecPath ?? "_not detected_"}
- Targeted specs green (agent-attested): ${finalIteration.testsPassed ? "yes" : "no"}

---

_Generated by \`@gohub/sentry-loop-orchestrator\`. CI must pass before merge._
`;
}

function defaultHardProof(iteration: FixIterationResult): string {
  const lines = [
    "### Regression test",
    iteration.regressionSpecPath
      ? `- Spec: \`${iteration.regressionSpecPath}\``
      : "- Spec: _add before merge if missing_",
    "",
    "### Test output",
    "```",
    iteration.testOutput.trim() || "_No test output captured._",
    "```",
  ];
  return lines.join("\n");
}
